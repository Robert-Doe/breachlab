#!/usr/bin/env node
/**
 * Parses the real module_19 payload bank (10 category HTML files, each with
 * a consistent .entry / .tags / .payload-block / .meta structure) into
 * webapp/src/payloadBank.generated.ts. Also folds in curated category-level
 * blurb/threat-model/docs content from payload-docs-data.mjs.
 *
 * Run with: node scripts/parse-payload-bank.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { CATEGORY_META } from "./payload-docs-data.mjs";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const webappRoot = join(__dirname, "..");
const courseRoot = join(webappRoot, "..");
const payloadsDir = join(courseRoot, "module_19", "payloads");

function decodeEntities(s) {
  return s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#x27;/g, "'")
    .replace(/&#x3D;/g, "=")
    .replace(/&amp;/g, "&");
}

function stripTags(s) {
  return s.replace(/<[^>]+>/g, "").trim();
}

function parseCategoryFile(fileName) {
  const html = readFileSync(join(payloadsDir, fileName), "utf8");
  const id = fileName.replace(/^\d+_/, "").replace(/\.html$/, "");

  // Track section labels in document order so each entry knows its subsection.
  const sectionMarkers = [...html.matchAll(/class="section-label">([^<]*)</g)].map((m) => ({
    index: m.index,
    label: m[1].trim(),
  }));

  function sectionFor(index) {
    let current = "";
    for (const marker of sectionMarkers) {
      if (marker.index < index) current = marker.label;
      else break;
    }
    return decodeEntities(current);
  }

  const entries = [];
  const entryRe = /<div class="entry">([\s\S]*?)<\/div>\s*<\/div>\s*(?=<!--|<div class="section-label"|<div class="nav")/g;
  // Simpler: split on entry blocks manually using a balanced-ish approach —
  // entries never nest, so match from '<div class="entry">' to the matching
  // close by counting the two known inner closes (.entry-header, .payload-block/.meta wrapper).
  const rawEntries = html.split('<div class="entry">').slice(1);

  for (const raw of rawEntries) {
    // Each entry block ends right before the next "<!-- P" comment, "<div class=\"section-label\"", or "<div class=\"nav\"".
    const endMatch = raw.search(/<!--\s*P\d+|<div class="section-label"|<div class="nav"/);
    const block = endMatch === -1 ? raw : raw.slice(0, endMatch);

    const tagMatches = [...block.matchAll(/class="tag ([^"]+)">([^<]*)</g)].map((m) => ({
      cls: m[1].replace(/^t-/, ""),
      label: m[2].trim(),
    }));

    const numMatch = block.match(/class="entry-num">(\d+)</);
    const num = numMatch ? Number(numMatch[1]) : entries.length + 1;

    const payloadMatch = block.match(/class="payload-block">(?:<button[^>]*>[^<]*<\/button>)?([\s\S]*?)<\/div>/);
    const payload = payloadMatch ? decodeEntities(payloadMatch[1].trim()) : "";

    const metaBlock = block.match(/class="meta">([\s\S]*?)<\/div>\s*<\/div>\s*$/);
    const meta = [];
    if (metaBlock) {
      const pairRe = /class="meta-key">([^<]*)<\/span><span class="meta-val[^"]*">([\s\S]*?)<\/span>/g;
      let m;
      while ((m = pairRe.exec(metaBlock[1]))) {
        meta.push({ key: m[1].trim(), value: decodeEntities(stripTags(m[2])) });
      }
    }

    if (!payload && meta.length === 0) continue; // skip anything that didn't parse

    // The course's own "Mechanism" field cites the 1-5 taxonomy number
    // already used by the live sandbox — reuse it to wire "run in sandbox".
    const mechMeta = meta.find((m) => m.key === "Mechanism");
    const mechNum = mechMeta ? (mechMeta.value.match(/^(\d)/) || [])[1] : null;
    const MECH_MAP = { 1: "tag-parsing", 2: "event-handlers", 3: "uri-schemes", 4: "dom-sinks", 5: "context-escape" };
    const sandboxMechanism = mechNum ? MECH_MAP[mechNum] ?? null : null;

    entries.push({
      num,
      section: sectionFor(html.indexOf(raw) + (endMatch === -1 ? 0 : 0)),
      tags: tagMatches,
      payload,
      meta,
      sandboxMechanism,
    });
  }

  return { id, entries };
}

const files = readdirSync(payloadsDir).filter((f) => /^\d+_.*\.html$/.test(f));
const categories = files
  .sort()
  .map((f) => {
    const parsed = parseCategoryFile(f);
    const meta = CATEGORY_META[parsed.id];
    if (!meta) throw new Error(`No CATEGORY_META entry for category "${parsed.id}" (from ${f})`);
    return { ...parsed, ...meta };
  });

const totalEntries = categories.reduce((n, c) => n + c.entries.length, 0);
console.log(`Parsed ${categories.length} categories, ${totalEntries} payload entries.`);

function tsString(s) {
  return JSON.stringify(s);
}

let out = "";
out += "// AUTO-GENERATED by scripts/parse-payload-bank.mjs — do not hand-edit.\n";
out += "// Source of truth: module_19/payloads/*.html (the real course payload bank).\n\n";
out += "export interface PayloadTag { cls: string; label: string }\n";
out += "export interface PayloadMeta { key: string; value: string }\n";
out += "export interface PayloadEntry { num: number; section: string; tags: PayloadTag[]; payload: string; meta: PayloadMeta[]; sandboxMechanism: string | null; severity: \"critical\" | \"high\" | \"medium\" | \"low\" }\n";
out += "export interface DocLink { title: string; description: string; url: string }\n";
out += "export interface PayloadCategory { id: string; title: string; blurb: string; rationale: string; threatModel: string; baseSeverity: \"critical\" | \"high\" | \"medium\" | \"low\"; docs: DocLink[]; entries: PayloadEntry[] }\n\n";

const ESCALATE_TAGS = new Set(["zeroclick", "cve", "worm", "chain", "impact", "bb"]);
const SEV_ORDER = ["low", "medium", "high", "critical"];

function severityFor(baseSeverity, tags) {
  const escalate = tags.some((t) => ESCALATE_TAGS.has(t.cls));
  if (!escalate) return baseSeverity;
  const idx = SEV_ORDER.indexOf(baseSeverity);
  return SEV_ORDER[Math.min(idx + 1, SEV_ORDER.length - 1)];
}

out += "export const PAYLOAD_BANK: PayloadCategory[] = [\n";
for (const cat of categories) {
  out += "  {\n";
  out += `    id: ${tsString(cat.id)},\n`;
  out += `    title: ${tsString(cat.title)},\n`;
  out += `    blurb: ${tsString(cat.blurb)},\n`;
  out += `    rationale: ${tsString(cat.rationale)},\n`;
  out += `    threatModel: ${tsString(cat.threatModel)},\n`;
  out += `    baseSeverity: ${tsString(cat.baseSeverity)},\n`;
  out += "    docs: [\n";
  for (const d of cat.docs) {
    out += `      { title: ${tsString(d.title)}, description: ${tsString(d.description)}, url: ${tsString(d.url)} },\n`;
  }
  out += "    ],\n";
  out += "    entries: [\n";
  for (const e of cat.entries) {
    out += `      { num: ${e.num}, section: ${tsString(e.section)}, tags: [${e.tags
      .map((t) => `{ cls: ${tsString(t.cls)}, label: ${tsString(t.label)} }`)
      .join(", ")}], payload: ${tsString(e.payload)}, meta: [${e.meta
      .map((m) => `{ key: ${tsString(m.key)}, value: ${tsString(m.value)} }`)
      .join(", ")}], sandboxMechanism: ${e.sandboxMechanism ? tsString(e.sandboxMechanism) : "null"}, severity: ${tsString(
      severityFor(cat.baseSeverity, e.tags)
    )} },\n`;
  }
  out += "    ],\n";
  out += "  },\n";
}
out += "];\n";

writeFileSync(join(webappRoot, "src", "payloadBank.generated.ts"), out, "utf8");
console.log("Wrote src/payloadBank.generated.ts");
